require "test_helper"
require_relative "../../test_helpers/acl_evaluator"

class Relay::CloudConfigTest < ActiveSupport::TestCase
  PEERS = [
    { "name" => "zenohd-home", "kind" => "router", "rw" => %w[asterism/** demo/**], "admin_space" => true, "in_acl" => true },
    { "name" => "console", "kind" => "client", "rw" => %w[asterism/**], "admin_space" => true, "in_acl" => true },
    { "name" => "viewer", "kind" => "client", "rw" => [], "ro" => %w[demo/** asterism/**], "in_acl" => true },
    { "name" => "w2.bot", "kind" => "client", "rw" => %w[asterism/**], "in_acl" => false },
    { "name" => "zenohd-cloud", "kind" => "router", "rw" => %w[x/**], "in_acl" => true },
    { "name" => "idle", "kind" => "client", "in_acl" => true }
  ].freeze

  def config
    Relay::CloudConfig.new(PEERS)
  end

  def rule(h, id)
    h["access_control"]["rules"].find { _1["id"] == id } || flunk("no rule #{id}")
  end

  test "TLS and the router part, as in W1" do
    h = config.to_h
    assert_equal [ "router", "zenohd-cloud", [ "tls/[::]:7448" ] ], [ h["mode"], h["metadata"]["name"], h["listen"]["endpoints"] ]
    tls = h["transport"]["link"]["tls"]
    assert_equal "/certs/zenohd-cloud.pem", tls["listen_certificate"]
    assert_equal "/certs/zenohd-cloud.key", tls["listen_private_key"]
    assert_equal [ true, true ], tls.values_at("enable_mtls", "close_link_on_expiration")
    assert_equal({ "read" => true, "write" => false }, h["adminspace"]["permissions"])
    assert_equal [ true, "deny" ], h["access_control"].values_at("enabled", "default_permission")
  end

  test "who is in the ACL: enabled with a certificate, not the cloud itself, with something allowed" do
    assert_equal %w[console viewer zenohd-home], config.subject_names
    h = config.to_h
    pol = h["access_control"]["policies"].to_h { [ _1["id"], _1["rules"] ] }
    assert_equal %w[zenohd_home_rw admin_relay_in admin_relay_out], pol["zenohd_home"]
    assert_equal %w[console_rw admin_read], pol["console"]
    assert_equal %w[viewer_ro_in viewer_ro_out], pol["viewer"]
    refute pol.key?("idle")
  end

  test "read and write, read only, the admin space" do
    h = config.to_h
    rw = rule(h, "zenohd_home_rw")
    assert_equal Relay::CloudConfig::ALL, rw["messages"]
    assert_equal %w[egress ingress], rw["flows"]
    assert_equal %w[asterism/** demo/**], rw["key_exprs"]
    ro_in = rule(h, "viewer_ro_in")
    assert_equal %w[ingress], ro_in["flows"]
    refute_includes ro_in["messages"], "put"
    refute_includes ro_in["messages"], "declare_queryable"
    assert_includes ro_in["messages"], "declare_subscriber"
    assert_equal %w[egress], rule(h, "viewer_ro_out")["flows"]
    assert_equal %w[query reply], rule(h, "admin_read")["messages"]
    assert_equal [ "@/**" ], rule(h, "admin_relay_in")["key_exprs"]
    assert_equal %w[egress], rule(h, "admin_relay_out")["flows"]
  end

  test "the file says it is generated, parses as JSON, and its subjects can be read back" do
    text = config.text(by: "admin@example.com", at: Time.utc(2026, 10, 9))
    assert text.start_with?("// GENERATED by asterism-console")
    assert_includes text, "digest #{config.digest}."
    json = JSON.parse(text.lines.reject { _1.start_with?("//") }.join)
    assert_equal config.to_h, json
    assert_equal config.subject_names, Relay::CloudConfig.subjects_of(text)
    assert_nil Relay::CloudConfig.subjects_of(nil)
    assert_equal config.digest, Relay::CloudConfig.new(PEERS.reverse).digest, "the order of the rows does not matter"
  end

  test "nobody: everything denied" do
    h = Relay::CloudConfig.new([]).to_h
    assert_equal({ "enabled" => true, "default_permission" => "deny", "rules" => [], "subjects" => [], "policies" => [] },
                 h["access_control"])
  end

  test "the connection limits (zenoh 1.10.1 names)" do
    h = Relay::CloudConfig.new([], { "max_sessions" => 8 }).to_h
    assert_equal({ "max_sessions" => 8, "accept_pending" => 16, "accept_timeout" => 5000 }, h["transport"]["unicast"])
    assert_equal 4 * 1024 * 1024, h["transport"]["link"]["rx"]["max_message_size"]
  end

  MATCH = { "name" => "match", "for_browsers" => true,
            "templates" => { "rw" => %w[asterism/${node} asterism/${node}/game/** asterism/${node}/@profile],
                             "read" => %w[asterism/* asterism/*/game/** asterism/*/@profile],
                             "ask" => %w[asterism/*/@profile asterism/*/game/*/meta asterism/*/game/*/call/${node}],
                             "watch" => %w[asterism/**] } }.freeze

  test "a role: node-bound templates per row, expanded to the nodes it speaks for; the rest shared" do
    peers = [
      { "name" => "alice", "kind" => "client", "roles" => %w[match], "in_acl" => true },
      { "name" => "home-bob", "kind" => "router", "roles" => %w[match], "nodes" => %w[fmruby-aaaaaa fmruby-bbbbbb],
        "in_acl" => true }
    ]
    h = Relay::CloudConfig.new(peers, {}, roles: [ MATCH ]).to_h
    assert_equal %w[asterism/alice asterism/alice/game/** asterism/alice/@profile], rule(h, "alice__match_rw")["key_exprs"]
    assert_equal Relay::CloudConfig::ALL, rule(h, "alice__match_rw")["messages"]
    assert_equal %w[asterism/fmruby-aaaaaa asterism/fmruby-bbbbbb asterism/fmruby-aaaaaa/game/** asterism/fmruby-bbbbbb/game/**
                    asterism/fmruby-aaaaaa/@profile asterism/fmruby-bbbbbb/@profile],
                 rule(h, "home_bob__match_rw")["key_exprs"]
    assert_equal %w[asterism/*/game/*/call/fmruby-aaaaaa asterism/*/game/*/call/fmruby-bbbbbb],
                 rule(h, "home_bob__match_ask")["key_exprs"], "calls only under its own nodes' names"
    assert_equal %w[query], rule(h, "home_bob__match_ask")["messages"]
    assert_equal %w[asterism/*/@profile asterism/*/game/*/meta], rule(h, "role__match_ask")["key_exprs"]
    read_in = rule(h, "role__match_read_in")
    assert_equal [ %w[ingress], %w[declare_subscriber liveliness_query] ], read_in.values_at("flows", "messages")
    assert_equal %w[egress], rule(h, "role__match_read_out")["flows"]
    assert_equal [ "asterism/**" ], rule(h, "role__match_watch")["key_exprs"]
    pol = h["access_control"]["policies"].to_h { [ _1["id"], _1["rules"] ] }
    assert_equal %w[alice__match_rw role__match_read_in role__match_read_out alice__match_ask role__match_ask
                    role__match_watch], pol["alice"]
    assert_equal 1, h["access_control"]["rules"].count { _1["id"] == "role__match_read_in" }, "shared rules once"
    refute h["access_control"]["rules"].any? { _1["key_exprs"].any? { |k| k.include?("demo") } }
  end

  test "an unknown role and a role with nothing give nothing" do
    peers = [ { "name" => "alice", "roles" => %w[gone empty], "in_acl" => true } ]
    h = Relay::CloudConfig.new(peers, {}, roles: [ { "name" => "empty", "templates" => {} } ]).to_h
    assert_equal [], h["access_control"]["subjects"]
  end

  test "what a row gets, for the pages" do
    c = Relay::CloudConfig.new([], {}, roles: [ MATCH ])
    e = c.expansion_for("name" => "home-a", "roles" => %w[match], "nodes" => %w[fmruby-aaaaaa])
    assert_equal %w[rw read ask watch], e.map { _1["section"] }
    assert_includes e.find { _1["section"] == "ask" }["keys"], "asterism/*/game/*/call/fmruby-aaaaaa"
    assert_equal [], c.expansion_for("name" => "x", "roles" => [])
  end

  test "browsers: a ws/ listener, one subject by link protocol, the roles for browsers on wasm-* nodes" do
    c = Relay::CloudConfig.new([], { "listen" => [ "tls/[::]:7448" ], "browsers" => "ws/[::]:7449" }, roles: [ MATCH ])
    h = c.to_h
    assert_equal [ "tls/[::]:7448", "ws/[::]:7449" ], h["listen"]["endpoints"]
    assert_includes h["access_control"]["subjects"], { "id" => "browsers", "link_protocols" => [ "ws" ] }
    assert_equal %w[asterism/wasm-$* asterism/wasm-$*/game/** asterism/wasm-$*/@profile], rule(h, "browsers__match_rw")["key_exprs"]
    assert_equal %w[asterism/*/game/*/call/wasm-$*], rule(h, "browsers__match_ask")["key_exprs"]
    assert_equal [], c.subject_names, "no certificate names for the browsers"
    refute Relay::CloudConfig.new([], {}, roles: [ MATCH ]).to_h["access_control"]["subjects"].any?, "none without the setting"
    other = Relay::CloudConfig.new([], { "browsers" => "ws/[::]:7449", "browser_nodes" => "web-$*" },
                                   roles: [ MATCH.merge("for_browsers" => false) ]).to_h
    refute other["access_control"]["subjects"].any?, "no role for browsers: no subject"
    prefixed = Relay::CloudConfig.new([], { "browsers" => "ws/[::]:7449", "browser_nodes" => "web-$*" }, roles: [ MATCH ]).to_h
    assert_includes rule(prefixed, "browsers__match_rw")["key_exprs"], "asterism/web-$*/game/**"
  end
  # The rooms' seats (0.3.0; from the rooms' store since 0.3.1, settings
  # "room_seats"), one seat in each of two slots.
  ROOMS = { "room_seats" => { "01" => %w[01], "02" => %w[01] } }.freeze

  test "room seats (G2): their slot's key space and its @adv part, nothing else; max_sessions 96" do
    h = Relay::CloudConfig.new(PEERS, ROOMS).to_h
    r = rule(h, "room_01_seats_in")
    assert_equal %w[room/01/** room/01/**/@adv/** room/01/asterism/*/@profile], r["key_exprs"]
    pol = h["access_control"]["policies"].to_h { [ _1["id"], _1["rules"] ] }
    assert_equal %w[room_01_seats_in room_01_seats_get room_01_seats_out room_01_seats_no_calls room_01_s01_own],
                 pol["room_01_s01"]
    assert_equal [ "room_01_s01_call" ], pol["room_01_s01_calls"]
    refute pol.key?("room_01"), "no certificate of a slot's own (0.3.1)"
    sub = h["access_control"]["subjects"].find { _1["id"] == "room_01_s01" }
    assert_equal [ "room-01-s01" ], sub["cert_common_names"]
    assert_equal 96, h["transport"]["unicast"]["max_sessions"]
  end

  ROOM_KEYS = %w[
    room/01/asterism/wasm-abc123 room/01/asterism/wasm-abc123/game room/01/asterism/wasm-abc123/game/table
    room/01/asterism/wasm-abc123/game/table/call/console room/01/asterism/wasm-abc123/game/table/meta
    room/01/asterism/wasm-abc123/@profile room/01/x room/01/** room/*/asterism/** room/02/asterism/wasm-def456/game
  ].freeze
  OUTSIDE_KEYS = %w[asterism/console/console asterism/alice/game/table asterism/** demo/x @/x/router room/**].freeze

  test "the console watches the rooms (0.2.1): liveliness only, nothing written, nothing called" do
    acl = Relay::CloudConfig.new(PEERS, ROOMS).access_control
    pol = acl["policies"].to_h { [ _1["id"], _1["rules"] ] }
    assert_equal %w[console_rw admin_read console__rooms_in console__rooms_out], pol["console"]
    allowed = []
    Relay::CloudConfig::ALL.each do |message|
      %w[ingress egress].each do |flow|
        ROOM_KEYS.each { |key| allowed << [ message, flow, key ] if AclEvaluator.allowed?(acl, "console", message, flow, key) }
      end
    end
    ins = allowed.select { _2 == "ingress" }.map(&:first).uniq.sort
    outs = allowed.select { _2 == "egress" }.map(&:first).uniq.sort
    assert_equal %w[declare_liveliness_subscriber liveliness_query], ins, "from the console: the watch only"
    assert_equal %w[liveliness_token reply], outs, "to the console: the tokens and the replies only"
    assert AclEvaluator.allowed?(acl, "console", "declare_liveliness_subscriber", "ingress", "room/*/asterism/**")
    assert AclEvaluator.allowed?(acl, "console", "liveliness_token", "egress", "room/02/asterism/wasm-def456/game")
    %w[put delete declare_queryable liveliness_token query declare_subscriber reply].each do |m|
      ROOM_KEYS.each { |key| refute AclEvaluator.allowed?(acl, "console", m, "ingress", key), "console #{m} into #{key}" }
    end
    refute AclEvaluator.allowed?(acl, "console", "liveliness_token", "egress", "room/01/asterism/wasm-abc123/@profile"),
           "@ chunks are not in **"
  end

  test "the rooms reach nothing outside their slot, also with the console watching them" do
    acl = Relay::CloudConfig.new(PEERS, ROOMS).access_control
    Relay::CloudConfig::ALL.each do |message|
      %w[ingress egress].each do |flow|
        (OUTSIDE_KEYS + ROOM_KEYS).each do |key|
          %w[room-01-s01 room-02-s01].each do |seat|
            next unless AclEvaluator.allowed?(acl, seat, message, flow, key)
            assert key.start_with?("room/#{seat[5, 2]}/"), "#{seat} #{message} #{flow} #{key}"
          end
        end
      end
    end
    refute AclEvaluator.allowed?(acl, "room-01-s01", "declare_liveliness_subscriber", "ingress", "room/*/asterism/**")
    refute AclEvaluator.allowed?(acl, :ws, "liveliness_token", "egress", "room/01/asterism/wasm-abc123/game")
    refute AclEvaluator.allowed?(acl, "viewer", "liveliness_token", "egress", "room/01/asterism/wasm-abc123/game")
  end

  test "no seats: the console has no rule for the rooms" do
    acl = Relay::CloudConfig.new(PEERS).access_control
    refute acl["rules"].any? { _1["id"].include?("rooms") }
    other = Relay::CloudConfig.new(PEERS, ROOMS.merge("console" => "ops")).access_control
    refute other["rules"].any? { _1["id"].include?("rooms") }, "only the console's own certificate"
  end
end
